# União
conjunto1 = {1, 2, 3}
conjunto2 = {2, 3, 4}
uniao = conjunto1.union(conjunto2)
print(uniao)

# Interseção

conjunto1 = {1, 2, 3}
conjunto2 = {2, 3, 4}
intersecao = conjunto1.intersection(conjunto2)
print(intersecao)

# Diferença

conjunto1 = {1, 2, 3}
conjunto2 = {2, 3, 4}
diferenca = conjunto1.difference(conjunto2)
print(diferenca)