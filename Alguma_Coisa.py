entrada = input("Digite alguma coisa: ")

print("È numerico? ", entrada.isnumeric())
print("È alfabetico? ", entrada.isalpha())
print("È alfanumerico? ", entrada.isalnum())
print("È decimal? ", entrada.isdecimal())
print("Possui apenas espaços? ", entrada.isspace())
print("Está em maiúsculo? ", entrada.isupper())
print("Está em minúsculo? ", entrada.islower())