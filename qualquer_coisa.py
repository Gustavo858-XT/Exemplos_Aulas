entrada = input("Digite qualquer coisa: ")
print("Tipo de dado: ", type(entrada))
print("È numerico?", entrada.isdigit())
print("apenas letras?", entrada.isalpha())
print("È alfanumerico?", entrada.isalnum())
print("Possui apenas espaços?", entrada.isspace())
print("Está em maiúsculo?", entrada.isupper())
print("Está em minúsculo?", entrada.islower())
print("está em formato de titulo?", entrada.istitle())